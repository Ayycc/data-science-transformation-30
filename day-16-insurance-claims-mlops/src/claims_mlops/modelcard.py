"""Model card generated from MLflow registry + run metadata (no hand-entered numbers)."""

from __future__ import annotations

import json
from pathlib import Path

from mlflow import MlflowClient

from claims_mlops import config as C


def write_model_card(
    client: MlflowClient, version: str, out: Path, model_name: str = C.MODEL_NAME, gate_policy: C.GatePolicy | None = None
) -> dict:
    mv = client.get_model_version(model_name, version)
    run = client.get_run(mv.run_id)
    params, metrics, tags = run.data.params, run.data.metrics, run.data.tags
    history = sorted(client.search_model_versions(f"name='{model_name}'"), key=lambda m: int(m.version))
    gate_policy = gate_policy or C.GatePolicy()
    card = {
        "model_name": model_name,
        "version": version,
        "stage": mv.current_stage,
        "aliases": list(getattr(mv, "aliases", []) or []),
        "run_id": mv.run_id,
        "family": tags.get("family"),
        "train_months": tags.get("train_months"),
        "trigger": tags.get("trigger", ""),
        "params": dict(params),
        "validation_metrics": {k.removeprefix("val_"): v for k, v in metrics.items() if k.startswith("val_")},
        "gate_tags": {"gate": mv.tags.get("gate"), "checks": json.loads(mv.tags.get("gate_checks", "{}"))},
    }
    vm = card["validation_metrics"]
    lines = [
        f"# Model card: `{model_name}` v{version}",
        "",
        "_Generated by `claims_mlops.modelcard` from MLflow registry and run metadata. Data is SYNTHETIC._",
        "",
        "## Model details",
        "",
        f"- **Registry stage / aliases:** {mv.current_stage} / {', '.join(card['aliases']) or '-'}",
        f"- **Family:** {card['family']} (Tweedie power {params.get('tweedie_power')}, log link), balanced so total predicted cost equals total observed cost on its training data",
        f"- **MLflow run:** `{mv.run_id}`",
        f"- **Training window (months):** {card['train_months']} ({params.get('n_train')} policies)",
        f"- **Why it was trained:** {card['trigger'] or 'initial training'}",
        "",
        "## Intended use",
        "",
        "Pure premium (expected claim cost per policy-year) for French motor third-party liability style policies, as a technical price input reviewed by the pricing team. Not for individual claims reserving, and not validated on real policyholders: all training data is SYNTHETIC.",
        "",
        "## Inputs",
        "",
        f"Numeric: {', '.join(C.NUM_FEATURES)}. Categorical: {', '.join(C.CAT_FEATURES)}. Weight: Exposure (policy-years). Contract enforced by Pydantic in `claims_mlops.api`.",
        "",
        "## Validation metrics (holdout logged to MLflow)",
        "",
        "| metric | value |",
        "|---|---|",
    ]
    for k in ("tweedie_deviance", "null_deviance", "gini", "ae_ratio", "mae", "balance_factor", "n_rows"):
        if k in vm:
            lines.append(f"| {k} | {vm[k]:.4g} |")
    lines += [
        "",
        "## Promotion gate",
        "",
        f"Policy: deviance gain over the champion on the same holdout greater than {gate_policy.min_rel_deviance_gain:.1%} (or the null model if none), Gini >= {gate_policy.min_gini}, A/E in [{gate_policy.ae_band[0]}, {gate_policy.ae_band[1]}].",
        f"Result recorded on the version: gate = **{card['gate_tags']['gate']}**, checks = {card['gate_tags']['checks']}.",
        "",
        "## Parameters",
        "",
        "| param | value |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in sorted(params.items())],
        "",
        "## Version history",
        "",
        "| version | family | stage | gate |",
        "|---|---|---|---|",
        *[f"| {h.version} | {h.tags.get('family')} | {h.current_stage} | {h.tags.get('gate')} |" for h in history],
        "",
        "## Caveats",
        "",
        "- SYNTHETIC data with an injected covariate shift and simulated claims inflation; metrics do not transfer to a real book.",
        "- Labels are assumed to be fully developed at month end; real claim costs take months to years to develop.",
        "- Fairness and regulatory review (e.g. gender-neutral pricing rules) are out of scope here.",
        "",
    ]
    out.write_text("\n".join(lines))
    return card
