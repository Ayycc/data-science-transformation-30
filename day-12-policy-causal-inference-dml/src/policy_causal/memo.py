"""Markdown outputs: a technical report and a plain-language policy memo, both generated from metrics."""

from __future__ import annotations

from pathlib import Path

import pandas as pd


def _usd(x: float) -> str:
    return f"${x:,.0f}"


def _pp(x: float) -> str:
    return f"{100 * x:.1f} pp"


def write_report(m: dict, est: pd.DataFrame, path: Path) -> None:
    a = m["acceptance"]
    lines = [
        "# Technical report: Day 12 causal analysis (SYNTHETIC data)",
        "",
        f"Seed {m['data']['seed']}; {m['data']['n_people']:,} SYNTHETIC people; {m['data']['n_counties']} SYNTHETIC counties x {m['data']['n_quarters']} quarters. Generated by `make run`.",
        "",
        "## Estimator comparison (95% CIs; truth = sample average treatment effect)",
        "",
        "| Outcome | Method | Estimate | 95% CI | Bias vs truth | Truth in CI |",
        "|---|---|---|---|---|---|",
    ]
    for _, r in est.iterrows():
        f = _usd if r["outcome"] == "earnings_post" else (lambda v: f"{v:.4f}")
        ci = f"[{f(r['ci_low'])}, {f(r['ci_high'])}]" if pd.notna(r["ci_low"]) else "n/a"
        lines.append(
            f"| {r['outcome']} | {r['method']} | {f(r['estimate'])} | {ci} | {f(r['bias'])} | {'yes' if r['truth_in_ci'] else 'no'} |"
        )
    lines += [
        "",
        f"True SATE: earnings {_usd(m['truth']['ate_earnings'])}, employment {m['truth']['ate_employment']:.4f}.",
        "",
        "## Refutations",
        "",
        "| Outcome | Test | Original | New effect | Rule | Passed |",
        "|---|---|---|---|---|---|",
    ]
    for y in ("earnings_post", "employed_post"):
        for k in ("placebo_treatment", "random_common_cause", "data_subset_80pct"):
            r = m["refutations"][y][k]
            lines.append(f"| {y} | {k} | {r['original']:.4f} | {r['new_effect']:.4f} | {r['pass_rule']} | {r['passed']} |")
    nc = m["refutations"]["negative_control_outcome"]
    lines.append(
        f"| prior_earn_2 | negative control outcome | - | {nc['estimate']:.2f} [{nc['ci_low']:.2f}, {nc['ci_high']:.2f}] | {nc['pass_rule']} | {nc['passed']} |"
    )
    d = m["did"]
    lines += [
        "",
        "## Staggered difference-in-differences",
        "",
        f"- True overall ATT: {d['true_att_overall']:.3f} pp.",
        f"- Callaway-Sant'Anna (never-treated controls): {d['cs_never_treated']['att_overall']:.3f} pp, 95% CI [{d['cs_never_treated']['att_overall_ci'][0]:.3f}, {d['cs_never_treated']['att_overall_ci'][1]:.3f}].",
        f"- Callaway-Sant'Anna (not-yet-treated controls): {d['cs_not_yet_treated']['att_overall']:.3f} pp.",
        f"- Static TWFE: {d['twfe_static']['estimate']:.3f} pp, 95% CI [{d['twfe_static']['ci_low']:.3f}, {d['twfe_static']['ci_high']:.3f}] (bias {d['twfe_bias']:.3f}).",
        f"- Pre-trend joint Wald test ({d['cs_never_treated']['pretrend_df']} pre-period coefficients): chi2 = {d['cs_never_treated']['pretrend_wald']:.2f}, p = {d['cs_never_treated']['pretrend_p']:.3f}.",
        f"- Post-period event-time CIs covering the truth: {100 * d['event_time_ci_coverage_post']:.0f}%.",
        "",
        "## Synthetic control (pilot county)",
        "",
        f"- Pre-period RMSPE {m['synthetic_control']['pre_rmspe']:.3f}; average post gap {m['synthetic_control']['avg_post_gap']:.3f} pp vs true {m['synthetic_control']['true_avg_post_effect']:.3f} pp; placebo-in-space p = {m['synthetic_control']['placebo_p_value']:.4f} ({m['synthetic_control']['n_donors']} donors).",
        "",
        "## Coverage study (headline LinearDML, fresh seeds)",
        "",
        *[
            f"- {y}: {v['replications']} replications, coverage {100 * v['coverage']:.0f}%, mean bias {v['mean_bias']:.4f}, mean CI width {v['mean_ci_width']:.4f}."
            for y, v in m["coverage_study"].items()
        ],
        "",
        "## E-values",
        "",
        f"- Employment: RR {m['evalues']['employment']['risk_ratio']:.3f}, E-value {m['evalues']['employment']['evalue_point']:.2f} (CI bound {m['evalues']['employment']['evalue_ci']:.2f}).",
        f"- Earnings: standardised difference {m['evalues']['earnings']['std_mean_diff']:.3f}, E-value {m['evalues']['earnings']['evalue_point']:.2f} (CI bound {m['evalues']['earnings']['evalue_ci']:.2f}).",
        "",
        f"Acceptance: earnings truth in CI = {a['earnings_truth_in_ci']}, employment truth in CI = {a['employment_truth_in_ci']}, refutations passed {a['refutation_tests_passed']}/{a['refutation_tests_reported']}.",
    ]
    path.write_text("\n".join(lines) + "\n")


def write_memo(m: dict, path: Path) -> None:
    a = m["acceptance"]
    sub = {r["group"]: r for r in m["cate"]["earnings_post"]["subgroups"]}
    tg = m["cate"]["earnings_post"]["targeting_top30"]
    d = m["did"]
    un, em = sub["unemployed at baseline"], sub["employed at baseline"]
    naive_est = next(r["estimate"] for r in m["estimates"] if r["outcome"] == "earnings_post" and r["family"] == "naive")
    direction = "*lowers*" if naive_est < 0 else "raises"
    naive_line = (
        f"- **The simple comparison gets the answer badly wrong.** Comparing enrolled with non-enrolled people suggests enrolment {direction} "
        f"earnings by {_usd(abs(naive_est))}, because the people who enrol were already earning less. That comparison is off by {_usd(abs(a['naive_bias_earnings']))}."
    )
    if a["refutation_tests_passed"] == a["refutation_tests_reported"]:
        refute_line = (
            f"- The result passed all {a['refutation_tests_reported']} stress tests. When enrolment was replaced with random labels, the estimated effect disappeared. "
            "Adding a made-up extra factor, or re-running on 80% of the data, barely moved it. The method also found no 'effect' on earnings from *before* the programme, "
            "which is what we would expect if it is working properly."
        )
    else:
        refute_line = f"- The result passed {a['refutation_tests_passed']} of {a['refutation_tests_reported']} stress tests; see the technical report for the ones that failed."
    cs_ = m["coverage_study"]
    if a["employment_truth_in_ci"]:
        cover_line = "- In this simulation both 95% ranges contain the true effect."
    else:
        cover_line = (
            f"- In this simulation the employment range narrowly missed the true effect ({_pp(m['truth']['ate_employment'])}): the estimate was {_pp(a['employment_ate'] - m['truth']['ate_employment'])} too high. "
            f"When the whole study was repeated on {cs_['employed_post']['replications']} fresh simulated populations, the range contained the truth "
            f"{100 * cs_['employed_post']['coverage']:.0f}% of the time for employment and {100 * cs_['earnings_post']['coverage']:.0f}% for earnings. A 95% range is expected to miss about 1 time in 20."
        )
    pre = d["cs_never_treated"]
    if pre["pretrend_p"] > 0.05:
        trend_line = (
            f"- Before launch, early-adopting counties were on employment trends that were not statistically different from those of counties that never adopted (p = {pre['pretrend_p']:.2f}). "
            "That supports the county comparison."
        )
    else:
        trend_line = f"- **Caution:** before launch, adopting counties were already on different employment trends (p = {pre['pretrend_p']:.3f}), so the county comparison should be read with care."
    lines = [
        "# Policy memo: did the job-training programme work?",
        "",
        "**Important:** this memo is written from a SYNTHETIC simulation built to test the analysis method. The numbers show what the method finds when the true answer is known; they are not findings about a real programme.",
        "",
        "## Bottom line",
        "",
        f"- **The programme raises earnings.** Enrolling raises next-year earnings by about **{_usd(a['earnings_ate'])} a year** on average (95% range {_usd(a['earnings_ci'][0])} to {_usd(a['earnings_ci'][1])}).",
        f"- **It raises employment.** The chance of being employed rises by about **{_pp(a['employment_ate'])}** (95% range {_pp(a['employment_ci'][0])} to {_pp(a['employment_ci'][1])}).",
        naive_line,
        f"- **County rollout data agree.** Counties that started the programme saw employment rates rise by about {d['cs_never_treated']['att_overall']:.2f} percentage points over the quarters after launch (95% range {d['cs_never_treated']['att_overall_ci'][0]:.2f} to {d['cs_never_treated']['att_overall_ci'][1]:.2f}). The effect grows the longer a county has run the programme.",
        "",
        "## Who benefits most",
        "",
        f"- People unemployed when they enrol gain about {_usd(un['cate_mean'])} a year, against {_usd(em['cate_mean'])} for people who already had a job.",
        f"- By age: about {_usd(sub['age < 30']['cate_mean'])} for under-30s, {_usd(sub['age 30-44']['cate_mean'])} for 30-44s and {_usd(sub['age 45+']['cate_mean'])} for people aged 45 and over.",
        f"- By schooling: about {_usd(sub['educ <= 11 (no diploma)']['cate_mean'])} for people with 11 or fewer years of school, against {_usd(sub['educ >= 14']['cate_mean'])} for people with 14 or more.",
        f"- If places are limited, offering them to the 30% of people with the highest predicted gain would deliver about {_usd(tg['true_effect_top_by_cate'])} per participant, against {_usd(tg['true_effect_random'])} if places were filled at random.",
        "",
        "## How sure are we?",
        "",
        refute_line,
        cover_line,
        f"- The main risk is a factor we cannot see, such as motivation, that drives both enrolment and earnings. That factor would have to be very strong to explain the result away: it would need to raise both the chance of enrolling and the chance of being employed by a factor of {m['evalues']['employment']['evalue_point']:.2f} (the E-value).",
        trend_line,
        "",
        "## Recommendation",
        "",
        "1. **Scale the programme**, starting with counties that have high unemployment.",
        "2. **Give enrolment priority** to people who are unemployed, younger, or have less formal education.",
        "3. **Roll out in stages** across counties and keep some later-start counties as a comparison group, so the effect can be measured again with real data.",
        "4. **Collect a motivation or job-readiness score at intake.** It is the most likely hidden factor, and recording it would remove the main remaining doubt.",
        "",
        "_Generated by `make run` from `results/metrics.json`._",
    ]
    path.write_text("\n".join(lines) + "\n")
