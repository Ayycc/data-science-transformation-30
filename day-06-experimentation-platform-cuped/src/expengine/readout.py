"""One-page Markdown readout per experiment."""

from __future__ import annotations

from expengine.simulate import METRICS

LABEL = {
    "sessions": "Sessions (14 d)",
    "converted": "Conversion (14 d)",
    "revenue": "Revenue per user (14 d)",
    "retained_w2": "Active in week 2",
}


def _pct(x: float, d: int = 2) -> str:
    return f"{x * 100:+.{d}f}%"


def _p(x: float) -> str:
    return "<0.0001" if x < 1e-4 else f"{x:.4f}"


def render_readout(r: dict) -> str:
    pm = r["primary_metric"]
    m = r["metrics"]
    srm = r["srm"]
    lines = [
        f"# {r['exp_id']}: {r['name']}",
        "",
        "> SYNTHETIC experiment generated by `expengine.simulate` (seeded). Ground truth is known and shown at the end.",
        "",
        f"**Hypothesis.** {r['hypothesis']}  ",
        f"**Primary metric.** {LABEL[pm]}. **Enrollment.** {r['enrollment_days']} days, "
        f"{r['n_control']:,} control / {r['n_treatment']:,} treatment users.",
        "",
        f"## Decision: {r['decision']}",
        "",
        "## 1. Trust checks",
        "",
        f"- **Sample-ratio mismatch:** treatment share {srm['share_treatment']:.4f} vs 0.5 designed; "
        f"chi-square {srm['chi2']:.2f}, p = {_p(srm['p_value'])} -> "
        + ("**FAILED (p < 0.001)**" if srm["flagged"] else "passed"),
    ]
    nov = r["novelty"]
    lines.append(
        f"- **Novelty check (sessions/day):** lift {_pct(nov['early_rel_lift'])} in exposure days 0-2 vs "
        f"{_pct(nov['late_rel_lift'])} in days 7-13 (decay p = {_p(nov['decay_p_value'])}) -> "
        + ("**novelty effect detected**" if nov["flagged"] else "no significant decay")
    )
    lines += [
        "",
        "## 2. Metrics (CUPED-adjusted, 95% CIs)",
        "",
        "| Metric | Control | Treatment | Lift (naive) | Lift (CUPED) | CUPED 95% CI | Variance cut | Always-valid p | First significant day |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for k in METRICS:
        c, nv = m[k]["cuped"], m[k]["naive"]
        tag = " (primary)" if k == pm else ""
        day = m[k]["first_reject_day"]
        lines.append(
            f"| {LABEL[k]}{tag} | {c['control_mean']:.4f} | {c['treatment_mean']:.4f} | {_pct(nv['rel_lift'])} | "
            f"{_pct(c['rel_lift'])} | [{_pct(c['rel_ci_low'])}, {_pct(c['rel_ci_high'])}] | "
            f"{c['variance_reduction'] * 100:.1f}% | {_p(m[k]['always_valid_p_final'])} | {day if day else '-'} |"
        )
    rt = r["ratio_revenue_per_session"]
    lines += [
        "",
        f"Revenue per session (ratio metric, delta-method SE): {rt['control_ratio']:.4f} -> {rt['treatment_ratio']:.4f}, "
        f"lift {_pct(rt['rel_lift'])} [{_pct(rt['rel_ci_low'])}, {_pct(rt['rel_ci_high'])}], p = {_p(rt['p_value'])}.",
        "",
        "## 3. Sequential monitoring (daily peeks)",
        "",
    ]
    fr, fn = m[pm]["first_reject_day"], m[pm]["first_naive_reject_day"]
    tr = r["trace"]
    p_naive_min = min(tr["p_naive"])
    lines.append(
        f"mSPRT always-valid p on the primary metric at the final look: {_p(m[pm]['always_valid_p_final'])}"
        + (f"; first crossed 0.05 on day {fr}." if fr else "; never crossed 0.05.")
        + " A naive daily z-test would first have crossed 0.05 on "
        + (f"day {fn}" if fn else "no day")
        + f" (minimum naive p over all looks {_p(p_naive_min)})."
    )
    b = r["bayes"]
    lines += ["", "## 4. Bayesian view", ""]
    if pm == "converted":
        lines.append(
            f"Beta-Binomial (Beta(1,1) priors): P(treatment better) = {b['prob_t_better']:.3f}; expected loss if shipped "
            f"{b['expected_loss_t']:.5f} (tolerance {b['loss_tolerance']:.5f}); lift 95% credible interval "
            f"[{_pct(b['rel_lift_ci_low'])}, {_pct(b['rel_lift_ci_high'])}]. Rule says: **{b['decision']}**."
        )
    else:
        lines.append(
            f"Normal posterior on the CUPED effect (flat prior): P(effect > 0) = {b['prob_positive']:.3f}; expected loss if "
            f"shipped {b['expected_loss_t']:.5f} (tolerance {b['loss_tolerance']:.5f}). Rule says: **{b['decision']}**."
        )
    lines += [
        "",
        "## 5. Segments (primary metric, BH-adjusted across slices)",
        "",
        "| Segment | Level | n | Lift | p | p (BH) |",
        "|---|---|---|---|---|---|",
    ]
    for h in r["hte"]:
        lines.append(
            f"| {h['segment']} | {h['level']} | {h['n']:,} | {_pct(h['rel_lift'])} | {_p(h['p_value'])} | {_p(h['p_bh'])}"
            + (" *" if h["significant_bh"] else "")
            + " |"
        )
    pw = r["power"]
    lines += [
        "",
        "## 6. Power",
        "",
        f"To detect a {pw['mde_rel'] * 100:.0f}% relative lift on the primary metric (80% power, alpha 0.05): "
        f"{pw['n_per_arm_naive']:,} users per arm without CUPED ({pw['days_naive']:.1f} days at this traffic) vs "
        f"{pw['n_per_arm_cuped']:,} with CUPED ({pw['days_cuped']:.1f} days).",
        "",
        "## 7. Ground truth (simulation only)",
        "",
        "| Metric | True lift | CUPED estimate | CUPED CI covers truth | Always-valid CI covers truth |",
        "|---|---|---|---|---|",
    ]
    for k in METRICS:
        lines.append(
            f"| {LABEL[k]} | {_pct(m[k]['true_rel'])} | {_pct(m[k]['cuped']['rel_lift'])} | "
            f"{'yes' if m[k]['cuped_ci_covers_truth'] else 'NO'} | {'yes' if m[k]['always_valid_ci_covers_truth'] else 'NO'} |"
        )
    if r["truth"]["users_dropped_by_bug"]:
        lines.append(f"\nThe planted logging bug dropped {r['truth']['users_dropped_by_bug']:,} treatment users.")
    return "\n".join(lines) + "\n"
