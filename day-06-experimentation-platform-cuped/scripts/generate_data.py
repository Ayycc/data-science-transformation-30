"""Write the committed SYNTHETIC sample (data/sample/e01_sample.csv.gz) used by the tests and the app.

The full portfolio (~440k users) is regenerated by `make run` into data/generated/ (git-ignored).
No public source is probed: experiment data with known true effects only exists in simulation.
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import replace
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from expengine.simulate import default_portfolio, generate_experiment  # noqa: E402

SAMPLE_USERS = 8_000


def build_sample(out_dir: Path) -> Path:
    spec = replace(default_portfolio()[0], n_users=SAMPLE_USERS, seed=601)
    df, _, truth = generate_experiment(spec)
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "e01_sample.csv.gz"
    df.to_csv(path, index=False, compression={"method": "gzip", "mtime": 0})
    manifest = {"source": "SYNTHETIC", "spec": spec.to_dict(), "rows": len(df), "truth": truth}
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2))
    return path


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=str(ROOT / "data" / "sample"))
    print(build_sample(Path(ap.parse_args().out)))


if __name__ == "__main__":
    main()
