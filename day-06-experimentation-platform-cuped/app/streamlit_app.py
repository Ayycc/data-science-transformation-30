"""Optional interactive analysis: `make app`. Defaults to the committed SYNTHETIC sample (E01, 8k users).

Upload any CSV with columns: variant (control/treatment), arrival_day, a metric column and a
pre-period covariate column.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
import streamlit as st

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from expengine.cuped import (  # noqa: E402
    cuped_estimate,
    diff_in_means,
    stats_from_sums,
)
from expengine.power import n_per_arm_means  # noqa: E402
from expengine.sequential import msprt_sequence  # noqa: E402
from expengine.srm import srm_test  # noqa: E402

st.set_page_config(page_title="Experiment readout", layout="wide")
st.title("Experiment readout: CUPED, sequential and SRM")
st.caption("Default data is SYNTHETIC (generated by expengine.simulate).")

upload = st.file_uploader("CSV (optional)", type=["csv", "gz"])
df = pd.read_csv(upload) if upload else pd.read_csv(ROOT / "data" / "sample" / "e01_sample.csv.gz")
numeric = [c for c in df.columns if pd.api.types.is_numeric_dtype(df[c]) and c not in ("user_id", "arrival_day")]
c1, c2, c3 = st.columns(3)
metric = c1.selectbox("Metric", numeric, index=numeric.index("sessions") if "sessions" in numeric else 0)
cov = c2.selectbox(
    "Pre-period covariate", numeric, index=numeric.index("pre_sessions") if "pre_sessions" in numeric else 0
)
tau_rel = c3.slider("mSPRT tau (share of control mean)", 0.01, 0.20, 0.05, 0.01)

t = df["variant"].eq("treatment").to_numpy()
srm = srm_test([int((~t).sum()), int(t.sum())], [0.5, 0.5])
st.subheader("Trust check")
st.write(f"SRM chi-square p = {srm.p_value:.4g} -> {'FAILED' if srm.flagged else 'passed'}")

y, x = df[metric].to_numpy(float), df[cov].to_numpy(float)
naive, cup = diff_in_means(y, t, metric=metric), cuped_estimate(y, x, t, metric=metric)
st.subheader("Effect")
st.dataframe(
    pd.DataFrame([naive.to_dict(), cup.to_dict()])[
        [
            "method",
            "control_mean",
            "treatment_mean",
            "rel_lift",
            "rel_ci_low",
            "rel_ci_high",
            "p_value",
            "variance_reduction",
        ]
    ]
)

days = df["arrival_day"].to_numpy()
n_looks = int(days.max()) + 1


def cum(mask: np.ndarray) -> dict:
    def bc(w):
        return np.cumsum(np.bincount(days[mask], weights=w, minlength=n_looks))

    return {
        "n": bc(np.ones(mask.sum())),
        "sy": bc(y[mask]),
        "syy": bc(y[mask] ** 2),
        "sx": bc(x[mask]),
        "sxx": bc(x[mask] ** 2),
        "sxy": bc(x[mask] * y[mask]),
    }


s = stats_from_sums(cum(~t), cum(t), cuped=True)
seq = msprt_sequence(s["diff"], s["var"], (tau_rel * naive.control_mean) ** 2)
st.subheader("Daily looks")
st.line_chart(pd.DataFrame({"naive p": seq["p_naive"], "always-valid p": seq["p_always_valid"]}))
st.write(
    f"First always-valid rejection: day {seq['first_reject_look'] + 1 if seq['first_reject_look'] is not None else '-'}"
)

st.subheader("Plan the next test")
mde = st.slider("Relative MDE", 0.005, 0.10, 0.02, 0.005)
sd = float(np.std(y[~t], ddof=1))
vr = max(min(cup.variance_reduction, 0.99), 0.0)
n0 = n_per_arm_means(sd, mde * naive.control_mean)
n1 = n_per_arm_means(sd, mde * naive.control_mean, variance_reduction=vr)
st.write(f"Users per arm: {n0:,} without CUPED, {n1:,} with CUPED.")
