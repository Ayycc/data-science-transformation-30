"""Markdown reports generated from metrics: reconciliation summary and migration playbook."""

from __future__ import annotations

from .rules import DIFFERENCES


def _usd(cents: int) -> str:
    return f"${cents / 100:,.2f}"


def reconciliation_md(m: dict) -> str:
    pr = m["parallel_run"]
    last = pr["per_close"][-1]
    out = [
        "# Reconciliation: legacy vs modern (SYNTHETIC data)", "",
        f"Parallel run over {pr['closes']} quarterly closes. Generated by `make run`.", "",
        "## Per close", "",
        "| Close | compat == legacy (all 3 outputs) | DuckDB == Polars | Unexplained differences | Report cells changed D4 / D2 / D3 / D1 / D5 / D6 | Legacy s | Modern s |",
        "|---|---|---|---|---|---|---|",
    ]  # fmt: skip
    for c in pr["per_close"]:
        ch = c["report_cells_changed_by"]
        out.append(f"| {c['close']} | {c['compat_equals_legacy']} | {c['duckdb_equals_polars']} | {c['unexplained_differences']} | "
                   f"{' / '.join(str(ch.get(d, 0)) for d in ['D4', 'D2', 'D3', 'D1', 'D5', 'D6'])} | {c['legacy_seconds']} | {c['modern_duckdb_seconds']} |")  # fmt: skip
    out += ["", f"## Final close ({last['close']}): datacompy, legacy vs modern TARGET", "",
            "| Output | Legacy rows | Modern rows | Rows only in one side | Rows with all columns equal | Unequal cells | Cells traced to D1-D6 | Untraced |",
            "|---|---|---|---|---|---|---|---|"]  # fmt: skip
    for t, v in last["final_vs_legacy"].items():
        tr = pr["final_close_trace"][t]
        out.append(f"| {t} | {v['rows_legacy']:,} | {v['rows_modern']:,} | {v['rows_only_legacy'] + v['rows_only_modern']} | {v['rows_all_columns_equal']:,} | "
                   f"{v['unequal_cells']:,} | {tr['traced_to_a_step']:,} of {tr['final_diff_cells']:,} | {tr['untraced']} |")  # fmt: skip
    out += ["", "## Monetary effect of each intentional difference (final close, all quarters)", "",
            "| ID | Change | Earned premium | Incurred | IBNR | OTHER-LOB earned |", "|---|---|---|---|---|---|"]  # fmt: skip
    titles = {d.did: d.title for d in DIFFERENCES}
    for did, v in m["impact_by_difference_final_close"].items():
        out.append(
            f"| {did} | {titles[did]} | {_usd(v['earned_premium_cents'])} | {_usd(v['incurred_cents'])} | {_usd(v['ibnr_cents'])} | {_usd(v['other_lob_earned_cents'])} |"
        )
    out += ["", "Predicates for each difference are in `rule_inventory.md`. A changed cell outside its predicate would count as unexplained.", ""]
    return "\n".join(out)


def playbook_md(m: dict) -> str:
    pr, tt, bs = m["parallel_run"], m["time_travel"], m["benchmark_summary"]
    n = pr["closes"]
    smax = max(r["scale"] for r in m["benchmark"])
    bmax = {r["engine"]: r for r in m["benchmark"] if r["scale"] == smax}
    crit = [
        ("C1", "Compat mode equals legacy exactly on every output", f"{pr['closes_compat_equals_legacy']}/{n} closes", pr["closes_compat_equals_legacy"] == n),
        ("C2", "Zero unexplained differences in the parallel run", f"{pr['unexplained_differences_total']} unexplained over {n} closes", pr["unexplained_differences_total"] == 0),
        ("C3", "Engine portability: DuckDB and Polars identical", f"{pr['closes_duckdb_equals_polars']}/{n} closes", pr["closes_duckdb_equals_polars"] == n),
        ("C4", "Every filed return reproducible from Iceberg", f"{tt['filed_quarter_reproduced']}/{n} from snapshots, {tt['rerun_from_time_travelled_inputs_reproduces_report']}/{n} from re-run inputs", tt["filed_quarter_reproduced"] == n),
        ("C5", "Rollback drill succeeds", str(tt["rollback_drill_ok"]), tt["rollback_drill_ok"]),
        ("C6", "Modern run no slower than legacy at the largest benchmarked volume",
         f"{bmax['legacy']['policies']:,} policies: {bs['scale_max_speedup_duckdb_vs_legacy']}x (DuckDB), {bs['scale_max_speedup_polars_vs_legacy']}x (Polars); "
         f"{m['data']['policies']:,} policies: {bs['scale_1_speedup_duckdb_vs_legacy']}x (DuckDB)",
         bmax["ibis-duckdb"]["wall_seconds"] <= bmax["legacy"]["wall_seconds"]),
        ("C7", "Business sign-off of D1-D6 by Finance and the Actuarial function", "manual, not automatable", None),
    ]  # fmt: skip
    rows = "\n".join(f"| {c} | {t} | {e} | {'PASS' if ok else ('manual' if ok is None else 'FAIL')} |" for c, t, e, ok in crit)
    return (
        f"""# Migration playbook: legacy SAS/Excel QRT -> Ibis + Iceberg

Generated by `make run` from `results/metrics.json`. SYNTHETIC data. Numbers below are from this run.

## 1. Parallel run (done here for {n} quarterly closes)

1. Land each close's newly booked source rows in Iceberg `raw.*` tables (append, tagged `close-<quarter>`).
2. Run the legacy chain (as-is) and the modern pipeline twice: **compat** (all intentional differences off) and **target** (all on).
3. Reconcile with datacompy on all three outputs (premium detail, claims detail, report). Compat must equal legacy exactly.
   Then switch on D1-D6 one at a time. Every changed cell must satisfy its documented predicate.
4. File the **legacy** return during the parallel run. Archive the modern return in Iceberg, tagged by close.
5. Log runtime, unexplained differences and restatements per close (`reconciliation.md`).

## 2. Cut-over criteria

| ID | Criterion | Evidence (this run) | Status |
|---|---|---|---|
{rows}

Cut over at the first close after two consecutive closes that pass every automated check (here: all {n}) and after C7 sign-off. File the modern
return; keep the legacy chain runnable for two more closes as a shadow.

## 3. Rollback

- **Bad modern run:** `table.manage_snapshots().rollback_to_snapshot(<close tag snapshot>)` on `reporting.quarterly_report`.
  It was drilled here: a run that zeroed earned premium was rolled back, and the table matched the last good close again ({tt["rollback_drill_ok"]}).
- **Re-file a past quarter:** read the `close-<quarter>` tag (time travel). {tt["filed_quarter_reproduced"]}/{n} filed returns reproduced
  exactly from snapshots, and {tt["rerun_from_time_travelled_inputs_reproduces_report"]}/{n} by re-running the pipeline on the raw tables as at that tag.
- **Back to legacy:** during the shadow period, the legacy chain is still scheduled. Re-point the filing to its output and open an
  incident for any unexplained difference.

## 4. Schema change

IBNR became mandatory from 2025Q1. The report table schema was evolved in place ({"; ".join(tt["schema_events"])}). Snapshots from earlier
closes still read with their original schema ({tt["schema_version_correct_at_each_close"]}/{n} closes had the right schema).

## 5. Restatements

Late-booked premium means the current table restates earlier quarters, while the filed version stays available by tag:

| Quarter | Cells restated in current table | Written premium restated | Earned premium restated |
|---|---|---|---|
"""
        + "\n".join(
            f"| {q} | {v['cells_restated']} | {_usd(v['written_restatement_cents'])} | {_usd(v['earned_restatement_cents'])} |"
            for q, v in tt["restatements_in_current_table"].items()
        )
        + "\n"
    )
