"""Render PORTFOLIO_REPORT.md, the tools matrix and the MkDocs site sources from a repo scan."""

from __future__ import annotations

import csv
import json
from collections import Counter
from pathlib import Path

from .scan import DEV_TOOLS, FAMILIES, FAMILY_OF, DayFacts

GITHUB = "https://github.com/Ayycc/data-science-transformation-30/tree/main"
PROV_LABEL = {
    "synthetic_by_design": "synthetic by design",
    "synthetic_fallback": "synthetic fallback (public source blocked)",
    "public_primary": "public data (headline)",
    "synthetic_plus_public": "synthetic + public supplement",
}


def fmt(value, kind: str) -> str:
    if value is None:
        return "n/a"
    if kind == "f2x":
        return f"{value:.2f}x"
    if kind == "f3":
        return f"{value:.3f}"
    if kind == "f4":
        return f"{value:.4f}"
    if kind == "pct":
        return f"{value:.1f}%"
    if kind == "pct_frac":
        return f"{100 * value:.1f}%"
    if kind == "pct_frac2":
        return f"{100 * value:.2f}%"
    if kind == "pct_frac3":
        return f"{100 * value:.3f}%"
    if kind == "usd":
        return f"${value:,.0f}" if abs(value) >= 100 else f"${value:,.2f}"
    if kind == "usd_k":
        return f"${value:,.0f}k"
    if kind == "int":
        return f"{int(value):,}"
    return str(value)


def metric_text(d: DayFacts) -> str:
    m = d.metric
    if not m:
        return "n/a"
    s = f"{m['label']}: **{fmt(m.get('value'), m['fmt'])}**"
    c = d.context
    if c and c.get("value") is not None:
        if c["label"] == "of":
            s += f" of {fmt(c['value'], c['fmt'])}"
        else:
            s += f" ({c['label']} {fmt(c['value'], c['fmt'])})"
    return s.replace("|", "\\|")


def tools_of(d: DayFacts) -> list[str]:
    return [t for t in d.tools if t not in DEV_TOOLS]


def summarise(days: list[DayFacts], ci_meta: dict | None) -> dict:
    all_pkgs = sorted({t for d in days for t in d.tools})
    tools = sorted({t for d in days for t in tools_of(d)})
    usage = Counter(t for d in days for t in tools_of(d))
    fams = {f: sorted(int(d.num) for d in days if any(FAMILY_OF.get(t) == f for t in d.tools)) for f in FAMILIES}
    prov = Counter(d.provenance.get("category", "unknown") for d in days)
    attempted = [d for d in days if d.provenance.get("attempted")]
    reachable = [d for d in days if d.provenance.get("reachable")]
    used_public = [d for d in days if d.provenance.get("category") in ("public_primary", "synthetic_plus_public")]
    ci_counts = Counter((d.ci or {}).get("conclusion", "pending (this commit)" if d.num == "30" else "not in snapshot") for d in days)
    unmet = [(d, u) for d in days for u in d.unmet]
    return {
        "projects": len(days),
        "tiers": dict(Counter(d.tier for d in days)),
        "domains": len({d.domain for d in days}),
        "distinct_packages_pinned": len(all_pkgs),
        "distinct_tools_excluding_test_lint": len(tools),
        "tool_usage_top": usage.most_common(15),
        "families_covered": sum(1 for v in fams.values() if v),
        "families": fams,
        "unmapped_tools": sorted(t for t in tools if t not in FAMILY_OF),
        "loc_python_code": sum(d.loc["python_code"] for d in days),
        "loc_python_tests": sum(d.loc["python_tests"] for d in days),
        "loc_sql": sum(d.loc["sql"] for d in days),
        "test_functions_static": sum(d.tests["test_functions"] for d in days),
        "test_cases_static": sum(d.tests["test_cases_static"] for d in days),
        "test_files": sum(d.tests["test_files"] for d in days),
        "days_with_computed_parametrize": sum(1 for d in days if d.tests["parametrize_unknown"]),
        "ci": dict(ci_counts),
        "ci_meta": ci_meta,
        "provenance": dict(prov),
        "public_attempted_days": [int(d.num) for d in attempted],
        "public_reachable_days": [int(d.num) for d in reachable],
        "public_used_days": [int(d.num) for d in used_public],
        "public_sources_attempted": sum(len(d.provenance["attempted"]) for d in attempted),
        "public_sources_reachable": sum(len(d.provenance["reachable"]) for d in reachable),
        "unmet_criteria": len(unmet),
        "unmet_days": sorted({int(d.num) for d, _ in unmet}),
        "offline_llm_days": [int(d.num) for d in days if d.offline_llm],
        "caveats": sum(len(d.caveats) for d in days),
        "metrics_json_present": sum(1 for d in days if d.has_metrics_json),
        "problems": {d.num: d.problems for d in days if d.problems},
    }


def render_report(days: list[DayFacts], s: dict, link_base: str = "..") -> str:
    L: list[str] = []
    a = L.append
    cm = s["ci_meta"] or {}
    n = s["projects"]
    a("# Portfolio Report: 30 Days, 30 Projects")
    a("")
    a(
        "Generated by `day-30-capstone-supply-chain-digital-twin/scripts/build_portfolio.py` (run by `make run`) from the committed "
        "files of every `day-*` folder: README.md, requirements.txt, results/metrics.json and tests/. Nothing in the other "
        "29 folders is re-run, and every number below is read from those files, not typed by hand."
    )
    a("")
    a("## Summary")
    a("")
    a("| Measure | Value |")
    a("|---|---|")
    a(f"| Projects scanned | **{n}** ({', '.join(f'{k}: {v}' for k, v in sorted(s['tiers'].items()))}) |")
    a(f"| Domains | {s['domains']} |")
    a(f"| Distinct pinned packages (all requirements.txt) | {s['distinct_packages_pinned']} |")
    a(
        f"| Distinct tools, excluding pytest/ruff/coverage | **{s['distinct_tools_excluding_test_lint']}** across {s['families_covered']} capability families |"
    )
    a(
        f"| Lines of code (non-blank, non-comment) | **{s['loc_python_code']:,}** Python source + {s['loc_python_tests']:,} Python tests + {s['loc_sql']:,} SQL |"
    )
    a(
        f"| Tests (static count) | **{s['test_functions_static']}** test functions in {s['test_files']} files, {s['test_cases_static']} cases counting literal parametrisation |"
    )
    ci_txt = ", ".join(f"{k}: {v}" for k, v in sorted(s["ci"].items()))
    a(f"| CI (GitHub Actions, last job per folder) | {ci_txt} |")
    a(f"| results/metrics.json present | {s['metrics_json_present']}/{n} |")
    a(
        f"| Public data | attempted in {len(s['public_attempted_days'])}/{n} projects ({s['public_sources_attempted']} sources); "
        f"reachable in {len(s['public_reachable_days'])} ({s['public_sources_reachable']} sources); used in results in {len(s['public_used_days'])} |"
    )
    a(f"| Acceptance criteria not met | **{s['unmet_criteria']}** across Days {', '.join(f'{x:02d}' for x in s['unmet_days'])} |")
    a(f"| LLM projects run only on the offline fallback (no API key) | Days {', '.join(f'{x:02d}' for x in s['offline_llm_days'])} |")
    a("")
    a("## Projects and headline metrics")
    a("")
    a("Key metric = one headline figure per project read from its `results/metrics.json` (JSON path in `src/portfolio/registry.yaml`).")
    a("Tests = static test functions / cases (README-stated count where the README gives one). LOC = Python source + tests + SQL.")
    a("")
    a("| Day | Project | Tier | Key metric (from results/metrics.json) | Tests | LOC | CI | Data |")
    a("|---|---|---|---|---|---|---|---|")
    for d in days:
        ci = (d.ci or {}).get("conclusion", "pending" if d.num == "30" else "n/a")
        stated = (
            f" ({d.readme_stated_tests} stated)" if d.readme_stated_tests and d.readme_stated_tests != d.tests["test_cases_static"] else ""
        )
        loc = d.loc["python_code"] + d.loc["python_tests"] + d.loc["sql"]
        a(
            f"| {d.num} | [{d.title}]({link_base}/{d.folder}/) | {d.tier.replace('Tier ', '')} | {metric_text(d)} | "
            f"{d.tests['test_functions']} / {d.tests['test_cases_static']}{stated} | {loc:,} | {ci} | {PROV_LABEL.get(d.provenance.get('category'), '?')} |"
        )
    a("")
    a("## Tools coverage matrix")
    a("")
    a(
        "Rows are projects, columns are capability families; a cell lists the project's pinned packages in that family (from its requirements.txt)."
    )
    a("")
    fam_names = [f for f in FAMILIES if f != "utilities"]
    short = {f: f.split(",")[0].split("&")[0].strip() for f in fam_names}
    a("| Day | " + " | ".join(short[f] for f in fam_names) + " |")
    a("|---|" + "---|" * len(fam_names))
    for d in days:
        cells = []
        for f in fam_names:
            ts = [t for t in d.tools if FAMILY_OF.get(t) == f]
            cells.append(", ".join(ts))
        a(f"| {d.num} | " + " | ".join(cells) + " |")
    a("| **projects** | " + " | ".join(str(len(s["families"][f])) for f in fam_names) + " |")
    a("")
    a("Most used tools (projects pinning them): " + ", ".join(f"{t} ({c})" for t, c in s["tool_usage_top"]) + ".")
    once = sorted(t for t in {t for d in days for t in tools_of(d)} if sum(t in tools_of(d) for d in days) == 1)
    a(
        f"{len(once)} tools appear in exactly one project. The full binary matrix is in `day-30-capstone-supply-chain-digital-twin/results/portfolio/tools_matrix.csv`."
    )
    if s["unmapped_tools"]:
        a(f"Packages not mapped to a family: {', '.join(s['unmapped_tools'])}.")
    a("")
    a("## Data provenance: public vs synthetic")
    a("")
    a("| Path | Projects | Days |")
    a("|---|---|---|")
    for cat, label in PROV_LABEL.items():
        ds = [d for d in days if d.provenance.get("category") == cat]
        a(f"| {label} | {len(ds)} | {', '.join(d.num for d in ds)} |")
    a("")
    a("Public sources attempted, and whether the build network reached them:")
    a("")
    a("| Day | Attempted | Reachable | Used in results |")
    a("|---|---|---|---|")
    for d in days:
        att = d.provenance.get("attempted") or []
        if not att:
            continue
        rch = d.provenance.get("reachable") or []
        used = "yes" if d.provenance.get("category") in ("public_primary", "synthetic_plus_public") else "no"
        a(f"| {d.num} | {', '.join(att)} | {', '.join(rch) or 'none (blocked)'} | {used} |")
    a("")
    a(
        f"In short: {len(s['public_attempted_days'])} of {n} projects tried a public source, {len(s['public_reachable_days'])} reached at least one, and "
        f"{len(s['public_used_days'])} used public data in their reported results (Days {', '.join(f'{x:02d}' for x in s['public_used_days'])}). "
        f"Every other number in the portfolio comes from a seeded synthetic generator and is labelled SYNTHETIC in its folder. "
        "Most blocks were HTTP 403 from the build environment's egress proxy, not the source itself; GitHub raw files and some S3 buckets were the hosts that usually got through."
    )
    a("")
    a("## Acceptance criteria that were not met")
    a("")
    a("Taken from each README's Limitations section; the quoted evidence string is checked against the README by the test suite.")
    a("")
    a("| Day | Criterion | Result | README evidence |")
    a("|---|---|---|---|")
    for d in days:
        for u in d.unmet:
            a(f'| {d.num} | {u["criterion"]} | {u["result"]} | "{u.get("evidence", "results/metrics.json acceptance")}" |')
    a("")
    a(
        f"LLM projects without a live model: Days {', '.join(f'{x:02d}' for x in s['offline_llm_days'])} implemented the Claude path behind an "
        "environment variable and tested it with fake clients, but no `ANTHROPIC_API_KEY` was available, so they report offline fallbacks only "
        "(rules extractor, extractive answers, rules planner). No LLM accuracy, cost or latency number exists anywhere in the portfolio."
    )
    a("")
    a("Other documented deviations and skipped stretch goals (criteria were met, but the README flags a gap):")
    a("")
    for d in days:
        for c in d.caveats:
            a(f"- Day {d.num}: {c['text']}.")
    a("")
    a("## Test results: how they were obtained")
    a("")
    a(
        f"- **Static count, not a re-run.** Running all 30 suites inside `make run` would take far longer than the 20-minute budget and need "
        f"every project's dependencies, so the report parses each `tests/test_*.py` with Python's `ast` module and counts `test*` functions "
        f"(module level and in `Test*` classes). Literal `@pytest.mark.parametrize` lists are multiplied out. {s['days_with_computed_parametrize']} "
        "project(s) parametrise over computed iterables, so their static case count is a lower bound; where a README states the collected "
        "count it is shown in brackets."
    )
    if cm:
        a(
            f"- **CI status** comes from a committed snapshot of the GitHub Actions API (`data/sample/ci_snapshot.json`, fetched {cm.get('fetched_at')} "
            f"with the `gh` CLI, {cm.get('runs_scanned')} workflow runs scanned). CI runs `make test` on Python 3.11 for each folder changed by a push, "
            "so the status shown is the last CI job for that folder. Day 30's own job runs after this commit is pushed, so it shows as pending here. "
            "Refresh with `make ci-snapshot` (needs network); the report itself builds offline."
        )
    a("")
    a("## Lessons learned")
    a("")
    for lesson in lessons(days, s):
        a(f"- {lesson}")
    a("")
    a("## Method notes")
    a("")
    a(
        "- Tools: every requirement line is parsed (extras, environment markers, direct URLs and index options handled); names are normalised (`PyYAML` -> `pyyaml`). Different pins of the same package count once."
    )
    a(
        "- Lines of code: non-blank lines that are not `#` comments in `.py` files, and not `--` comments in `.sql` files, excluding `data/`, `results/`, `docs/` and caches. Docstrings count as code."
    )
    a(
        "- Key metrics, provenance, unmet criteria and caveats are curated in `src/portfolio/registry.yaml`; tests check every metric path resolves and every evidence quote appears in the README."
    )
    a("")
    return "\n".join(L)


def lessons(days: list[DayFacts], s: dict) -> list[str]:
    blocked = len(s["public_attempted_days"]) - len(s["public_reachable_days"])
    return [
        f"**Design for the network you have.** {blocked} of {len(s['public_attempted_days'])} projects that tried a public source could not reach any of it. "
        "The pattern used throughout was: probe, record the result in metrics.json, fall back to a seeded generator automatically, and say so in the README. "
        "Writing the public adapter anyway (Days 21, 24, 25, 26) kept the real-data path one environment variable away.",
        "**Synthetic data buys ground truth, and costs realism.** Known truth let projects check that estimators recover planted effects (DML ATE, MMM ROAS, promo lift here) "
        "rather than just fit well. The same author wrote the generator and the model in most projects, so headline accuracy is an upper bound; the READMEs say this, and the report keeps that caveat.",
        f"**Say when a criterion fails.** {s['unmet_criteria']} acceptance criteria were missed across {len(s['unmet_days'])} projects and are reported as missed, with what was tried. "
        "Several are close calls on one seed (Day 12) or within noise (Day 21), which is exactly when it is tempting to round up.",
        "**Pin for the CI interpreter, not the laptop.** Several projects needed environment markers because a newer wheel had no Python 3.11 build (scipy 1.18, shap 0.53, statsforecast 2.1). "
        f"CI ran on 3.11 for every folder and the last job passed for {s['ci'].get('success', 0)} of {sum(s['ci'].values())} folders.",
        "**Heavy optional dependencies need a plan B.** Hugging Face and, in some builds, PyTorch's CPU index were blocked, so projects re-implemented the method (Day 25's copula and CTGAN-style GAN), "
        "used a weaker substitute (Days 11 and 21 used spaCy vectors instead of sentence-transformers), or skipped an optional comparison to stay torch-free (Day 13 GNN). Each substitution is recorded.",
        "**LLM features must degrade gracefully.** All three LLM projects shipped a deterministic offline path with the same interface and fake-client tests. "
        "That kept them runnable and testable, but it also means the portfolio has no measured LLM result; that gap is stated, not papered over.",
        "**Decision systems beat point models.** The later projects (MMM budget optimiser, bandits, this digital twin) report decisions with uncertainty (HDIs, CVaR, probability of beating baseline) "
        "and evaluate the chosen policy on fresh seeds, which avoids selecting a winner on its own noise.",
    ]


def write_tools_matrix(days: list[DayFacts], path: Path) -> None:
    tools = sorted({t for d in days for t in d.tools})
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["tool", "family", "n_projects"] + [d.num for d in days])
        for t in tools:
            row = [int(t in d.tools) for d in days]
            w.writerow([t, FAMILY_OF.get(t, "test & lint" if t in DEV_TOOLS else "other"), sum(row)] + row)


def write_docs(days: list[DayFacts], s: dict, report_md: str, docs: Path, mkdocs_yml: Path) -> list[str]:
    """MkDocs sources: home page, the report, and one page per project. Returns written paths."""
    (docs / "projects").mkdir(parents=True, exist_ok=True)
    written = []
    home = [
        "# 30 Days, 30 Projects",
        "",
        f"Index of the {s['projects']} projects in the portfolio. Each page summarises the project from its committed files and links to the folder on GitHub.",
        "See the [portfolio report](portfolio-report.md) for the tools matrix, provenance and unmet criteria.",
        "",
        "| Day | Project | Tier | Domain | Key metric |",
        "|---|---|---|---|---|",
    ]
    for d in days:
        home.append(f"| {d.num} | [{d.title}](projects/day-{d.num}.md) | {d.tier.replace('Tier ', '')} | {d.domain} | {metric_text(d)} |")
    (docs / "index.md").write_text("\n".join(home) + "\n")
    written.append("index.md")
    (docs / "portfolio-report.md").write_text(report_md.replace("](../", f"]({GITHUB}/"))
    written.append("portfolio-report.md")
    for d in days:
        p = [
            f"# Day {d.num}: {d.title}",
            "",
            f"**{d.tier}** | **Domain:** {d.domain} | [Folder on GitHub]({GITHUB}/{d.folder}/) | [README]({GITHUB}/{d.folder}/README.md)",
            "",
            f"- **Key metric:** {metric_text(d)}",
            f"- **Data:** {PROV_LABEL.get(d.provenance.get('category'), '?')}"
            + (
                f"; public sources attempted: {', '.join(d.provenance['attempted'])}; reachable: {', '.join(d.provenance['reachable']) or 'none'}"
                if d.provenance.get("attempted")
                else ""
            ),
            f"- **Tests (static):** {d.tests['test_functions']} functions, {d.tests['test_cases_static']} cases"
            + (f" ({d.readme_stated_tests} stated in README)" if d.readme_stated_tests else ""),
            f"- **Lines of code:** {d.loc['python_code']:,} Python source, {d.loc['python_tests']:,} tests, {d.loc['sql']:,} SQL",
            f"- **CI:** {(d.ci or {}).get('conclusion', 'pending' if d.num == '30' else 'n/a')}",
            f"- **Tools:** {', '.join(tools_of(d))}",
            "",
        ]
        if d.unmet:
            p += ["## Acceptance criteria not met", ""] + [f"- {u['criterion']}: {u['result']}" for u in d.unmet] + [""]
        if d.caveats or d.offline_llm:
            p += ["## Caveats", ""] + [f"- {c['text']}" for c in d.caveats] + [""]
        (docs / "projects" / f"day-{d.num}.md").write_text("\n".join(p))
        written.append(f"projects/day-{d.num}.md")
    nav = ["  - Home: index.md", "  - Portfolio report: portfolio-report.md", "  - Projects:"]
    nav += [f'      - "Day {d.num}: {d.title.replace(chr(34), "")}": projects/day-{d.num}.md' for d in days]
    mkdocs_yml.write_text(
        "\n".join(
            [
                "# Generated by scripts/build_portfolio.py. Built offline with the built-in readthedocs theme (no CDN, no plugins).",
                "site_name: 30 Days, 30 Projects - Data Science Portfolio",
                "site_description: Index of 30 end-to-end data science projects",
                "repo_url: https://github.com/Ayycc/data-science-transformation-30",
                "edit_uri: ''",
                "docs_dir: docs",
                "site_dir: site",
                "theme:",
                "  name: readthedocs",
                "  highlightjs: false",
                "  navigation_depth: 2",
                "use_directory_urls: false",
                "strict: true",
                "nav:",
                *nav,
                "",
            ]
        )
    )
    return written


def write_summary(s: dict, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(s, indent=2) + "\n")
