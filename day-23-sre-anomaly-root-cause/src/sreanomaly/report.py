"""Markdown outputs: results/report.md (tables from metrics.json) and results/incident_timelines.md
(auto-generated incident timeline summaries, a stretch goal)."""

from __future__ import annotations

from pathlib import Path

from . import rca
from .generate import Telemetry


def clock(minute: int) -> str:
    d, m = divmod(int(minute), 1440)
    return f"day {d + 1} {m // 60:02d}:{m % 60:02d}"


def write_report(results_dir: Path, m: dict) -> None:
    L = ["# Day 23 results (SYNTHETIC telemetry)", "", "Generated by `make run` from `results/metrics.json`.", ""]
    L += ["## Detection (test period, after the 2-day training window)", ""]
    L += [
        "| detector / grouping | groups | precision | recall | median delay (min) | p90 delay (min) | incidents merged |",
        "|---|---|---|---|---|---|---|",
    ]
    for k, v in m["detection"]["by_detector"].items():
        L.append(
            f"| {k} | {v['n_groups']} | {v['precision']:.3f} | {v['recall']:.3f} | {v['delay_median_min']} | {v['delay_p90_min']} | {v.get('incidents_merged_into_one_group', '-')} |"
        )
    L += ["", f"Primary detector: **{m['detection']['primary_detector']}** ({m['detection']['selection']}).", ""]
    L += [
        "ECOD sensitivity (topological grouping):",
        "",
        "| quantile | persistence (min) | precision | recall | median delay | groups |",
        "|---|---|---|---|---|---|",
    ]
    for r in m["detection"]["ecod_sensitivity"]:
        L.append(f"| {r['quantile']} | {r['persistence']} | {r['precision']:.3f} | {r['recall']:.3f} | {r['delay_median_min']} | {r['n_groups']} |")
    a = m["alert_volume"]
    L += ["", "## Alert volume", "", "| stage | count |", "|---|---|"]
    for k in ("raw_metric_alerts", "per_service_episodes", "grouped_incidents_topological", "grouped_incidents_temporal_only", "injected_incidents"):
        L.append(f"| {k} | {a[k]} |")
    L += ["", f"Reduction raw alerts -> incidents: **{a['reduction_raw_to_incidents_pct']}%**.", ""]
    rc = m["root_cause"]
    L += [
        "## Root cause",
        "",
        f"Evaluated on {rc['evaluated_incidents']} detected injected incidents (root in candidate set: {rc['root_in_candidate_set']}; mean candidates {rc['mean_candidates']}).",
        "",
    ]
    L += ["| method | top-1 (detected) | top-3 (detected) | top-1 (all injected) | top-3 (all injected) |", "|---|---|---|---|---|"]
    for k, v in rc["methods"].items():
        L.append(f"| {k} | {v['top1_detected']:.3f} | {v['top3_detected']:.3f} | {v['top1_all_injected']:.3f} | {v['top3_all_injected']:.3f} |")
    dp = rc["deploy_prior"]
    L += ["", f"Deploy prior: {dp['window']}; leave-one-out likelihood ratio median {dp['likelihood_ratio_loo_median']}.", ""]
    L += ["| method / incident type | n | top-1 without prior | top-1 with prior |", "|---|---|---|---|"]
    for k, v in dp["by_incident_type"].items():
        L.append(f"| {k} | {v['n']} | {v['top1_without_prior']:.3f} | {v['top1_with_prior']:.3f} |")
    L += [
        "",
        "## Change-point onset accuracy (affected services in detected incidents)",
        "",
        "| method | evaluated | onset found | MAE (min) | median abs err (min) | root median abs err (min) |",
        "|---|---|---|---|---|---|",
    ]
    for k, v in m["change_points"].items():
        L.append(
            f"| {k} | {v['affected_services_evaluated']} | {v['onset_found_share']:.3f} | {v['onset_mae_min']} | {v['onset_median_abs_err_min']} | {v['root_onset_median_abs_err_min']} |"
        )
    pub = m.get("public_nab")
    if pub and pub.get("path_used") == "public_nab":
        L += [
            "",
            "## Public sanity check: NAB (real data, detectors only)",
            "",
            "| detector | windows hit | window recall | false-alarm episodes | per 1k points |",
            "|---|---|---|---|---|",
        ]
        for k, v in pub["totals"].items():
            L.append(
                f"| {k} | {v['windows_hit']}/{v['n_windows']} | {v['window_recall']:.3f} | {v['false_alarm_episodes']} | {v['false_alarms_per_1k_points']} |"
            )
    elif pub:
        L += ["", f"Public NAB check skipped: {pub.get('reason')}"]
    (results_dir / "report.md").write_text("\n".join(L) + "\n")


def write_timelines(results_dir: Path, rows: list[dict], tel: Telemetry, n: int = 12) -> None:
    """Template-based incident summaries an on-call engineer could paste into a ticket."""
    from .pipeline import loo_likelihood_ratio

    L = ["# Incident timelines (auto-generated, SYNTHETIC)", "", f"First {n} detected incidents. Ranking = ensemble + deploy prior.", ""]
    dep = tel.deploys
    for r in rows[:n]:
        post = rca.apply_deploy_prior(r["scores"]["ensemble"], r["deployed"], loo_likelihood_ratio(rows, r["incident_id"]))
        top = sorted(post, key=lambda c: (-post[c], c))[:3]
        ons = {s: o for s, o in r["onsets"]["pelt"].items() if o is not None}
        order = sorted(ons, key=lambda s: ons[s])[:5]
        near = dep[(dep["minute"] >= r["first_alert"] - 30) & (dep["minute"] <= r["first_alert"] + 5)]
        L.append(f"## Incident {r['incident_id']}: {clock(r['first_alert'])}")
        L.append("")
        L.append(f"- **First alert** {clock(r['first_alert'])}; {len(r['group_services'])} services alerting: {', '.join(r['group_services'])}.")
        if order:
            L.append("- **Change-point onsets (PELT)**: " + " -> ".join(f"{s} ({clock(ons[s])[-5:]})" for s in order) + ".")
        if len(near):
            L.append("- **Deploys nearby**: " + ", ".join(f"{d.service} at {clock(d.minute)[-5:]}" for d in near.itertuples()) + ".")
        else:
            L.append("- **Deploys nearby**: none in the 30 minutes before the first alert.")
        conf = 100 * post[top[0]] / sum(post.values())
        L.append(f"- **Likely root cause**: {top[0]} ({conf:.0f}% of posterior mass), then {', '.join(top[1:]) or '-'}.")
        verdict = "correct" if top[0] == r["root"] else ("in top 3" if r["root"] in top else "missed")
        L.append(f"- *Ground truth (synthetic)*: {r['root']} / {r['fault']}, injected {clock(r['start'])[-5:]} -> {verdict}.")
        L.append("")
    (results_dir / "incident_timelines.md").write_text("\n".join(L))
