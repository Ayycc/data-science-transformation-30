def write_examples(m: dict, out: Path) -> None:
    E = m["explanations"]
    lines = [
        "# Sample adverse-action explanations (generated by `make run`)",
        "",
        ("Applicants are SYNTHETIC. " if m["data"]["synthetic"] else "")
        + "The first three declined applicants of the out-of-time test set, with the four principal reasons (SHAP, log-odds of default) and the lowest-cost counterfactual on the search grid.",
        "",
        "Reason code table: " + "; ".join(f"{k} {v}" for k, v in E["reason_code_table"].items()) + ".",
        "",
    ]
    for ex in E["examples"]:
        lines += [
            f"## Application {ex['application_id']} (predicted default probability {_p(ex['p_bad'])})",
            "",
            "Principal reasons for the decision:",
            "",
        ]
        for i, (code, text, v) in enumerate(ex["reasons"], 1):
            lines.append(f"{i}. **{code}** {text} (SHAP +{v:.3f})" if v >= 0 else f"{i}. **{code}** {text} (SHAP {v:.3f})")
        lines += ["", f"What would have changed the decision: {ex['counterfactual'] or 'no change within the actionable bounds is sufficient'}.", ""]
        lines.append(
            "Inputs: "
            + ", ".join(
                (f"{k}={v:,.0f}" if abs(v) >= 1000 else f"{k}={v:.3g}") if isinstance(v, float) else f"{k}={v}" for k, v in ex["inputs"].items()
            )
        )
        lines.append("")
    (out / "adverse_action_examples.md").write_text("\n".join(lines))


def write_all(m: dict, out: Path) -> None:
    write_report(m, out)
    write_mdd(m, out)
    write_model_card(m, out)
    write_examples(m, out)
