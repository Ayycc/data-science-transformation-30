"""Generated documents: results report, SR 11-7-style model development document, model card, sample adverse-action notices.

Every number in these documents is read from the metrics dictionary produced by the same run.
"""

from __future__ import annotations

from pathlib import Path


def _p(x: float | None, d: int = 1) -> str:
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def _f(x: float | None, d: int = 3) -> str:
    return "n/a" if x is None else f"{x:.{d}f}"


def _ci(c: list[float], d: int = 3) -> str:
    return f"[{c[0]:.{d}f}, {c[1]:.{d}f}]"


def model_table(m: dict, keys: list[str] | None = None) -> str:
    M = m["models"]
    keys = keys or list(M)
    head = "| Model | Family | Test AUC | AUC vs unbiased label | Approval | Bad rate approved | Balanced acc. | Min AIR [95% CI] | DP diff | EO diff | Uses group at decision |\n|---|---|---|---|---|---|---|---|---|---|---|\n"
    rows = []
    for k in keys:
        r = M[k]
        t, f = r["test"], r["fairness"]
        rows.append(
            f"| `{k}` | {r['family']} | {_f(t.get('auc'))} | {_f(t.get('auc_vs_unbiased_label'))} | {_p(t['approval_rate'])} | {_p(t['bad_rate_approved'])} | "
            f"{_f(t['balanced_accuracy'])} | {_f(f['air_min'])} {_ci(f['air_min_ci'])} | {_f(f['dp_difference'])} | {_f(f['eo_difference'])} | "
            f"{'yes' if r['uses_protected_attribute_at_decision'] else 'no'} |"
        )
    return head + "\n".join(rows) + "\n"


def group_table(m: dict, keys: list[str]) -> str:
    M = m["models"]
    groups = sorted(M[keys[0]]["fairness"]["approval_rate"])
    head = (
        "| Model | "
        + " | ".join(f"Approval {g}" for g in groups)
        + " | "
        + " | ".join(f"AIR {g} [95% CI]" for g in groups if g in M[keys[0]]["fairness"]["air"])
        + " |\n"
    )
    head += "|---" * (1 + len(groups) + len(M[keys[0]]["fairness"]["air"])) + "|\n"
    rows = []
    for k in keys:
        f = M[k]["fairness"]
        rows.append(
            f"| `{k}` | "
            + " | ".join(_p(f["approval_rate"][g]) for g in groups)
            + " | "
            + " | ".join(f"{_f(f['air'][g])} {_ci(f['air_ci'][g])}" for g in groups if g in f["air"])
            + " |"
        )
    return head + "\n".join(rows) + "\n"


