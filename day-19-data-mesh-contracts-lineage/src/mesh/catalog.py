"""Data product catalogue (Markdown + static HTML) generated from contracts, SLO results and lineage."""

from __future__ import annotations

import html
from typing import Any

import networkx as nx

from mesh import contracts as C


def consumers_of(dg: nx.DiGraph, dataset: str) -> list[str]:
    if dataset not in dg:
        return []
    return sorted({dg.edges[dataset, s]["job"] for s in dg.successors(dataset)})


def deprecation_report(dg: nx.DiGraph) -> list[dict[str, Any]]:
    out = []
    for domain in C.PRODUCTS:
        cur = C.current(domain)
        for phys, ic, dep in C.published_interfaces(cur):
            if dep is None:
                continue
            ds = f"{domain}.main.{phys}"
            readers = [j for j in consumers_of(dg, ds) if not j.startswith(f"{domain}.")]
            out.append(
                {
                    "interface": ds,
                    "contract_version": ic["version"],
                    "superseded_by": f"{C.obj(cur)['physicalName']} ({cur['version']})",
                    "deprecation_date": dep,
                    "downstream_jobs_still_reading": readers,
                    "safe_to_retire": not readers,
                }
            )
    return out


def render(slo_reports: list[dict[str, Any]], dg: nx.DiGraph) -> tuple[str, str]:
    slo_by = {r["domain"]: r for r in slo_reports}
    md = [
        "# Data product catalogue",
        "",
        "Generated by `make run` from `contracts/`, SLO checks and OpenLineage events. All data is SYNTHETIC.",
        "",
    ]
    h = [
        "<!doctype html><html><head><meta charset='utf-8'><meta name='viewport' content='width=device-width,initial-scale=1'>",
        "<title>Data Product Catalogue</title><style>",
        ":root{--bg:#fff;--fg:#1d2329;--muted:#5b6670;--line:#d9dee3;--ok:#1f7a4d;--bad:#b3261e}",
        "@media (prefers-color-scheme:dark){:root{--bg:#14171a;--fg:#e6e9ec;--muted:#9aa3ad;--line:#2c3238;--ok:#5cc28f;--bad:#f2867e}}",
        "body{background:var(--bg);color:var(--fg);font:15px/1.5 system-ui,sans-serif;margin:0 auto;max-width:980px;padding:24px 16px}",
        "table{border-collapse:collapse;width:100%;margin:8px 0 20px;font-size:13px;display:block;overflow-x:auto}",
        "th,td{border-bottom:1px solid var(--line);padding:4px 8px;text-align:left;white-space:nowrap}",
        ".PASS{color:var(--ok);font-weight:600}.FAIL{color:var(--bad);font-weight:600}.muted{color:var(--muted)}",
        "</style></head><body><h1>Data product catalogue</h1>",
        "<p class='muted'>Generated from contracts, SLO checks and OpenLineage events. All data is SYNTHETIC.</p>",
    ]
    for domain in C.PRODUCTS:
        c = C.current(domain)
        r = slo_by.get(domain)
        ifaces = C.published_interfaces(c)
        md += [f"## {c['name']} (`{domain}`)", ""]
        md += [f"- **Contract:** `{c['id']}` version **{c['version']}** ({c['status']})"]
        md += [f"- **Owner:** {C.owner(c)} (team `{c['team']['name']}`)"]
        md += [f"- **Purpose:** {c['description']['purpose']}"]
        for phys, ic, dep in ifaces:
            ds = f"{domain}.main.{phys}"
            cons = ", ".join(f"`{j}`" for j in consumers_of(dg, ds) if not j.startswith(f"{domain}.")) or "none"
            tag = f" - DEPRECATED, retire after {dep}" if dep else " - latest"
            md += [f"- **Interface** `{ds}` (contract {ic['version']}){tag}. Downstream jobs: {cons}"]
        if r:
            md += [
                "",
                f"SLO status: **{r['status']}** ({r['passed']}/{r['total']})",
                "",
                "| SLA | target | observed | status |",
                "|---|---|---|---|",
            ]
            for ch in r["checks"]:
                md += [f"| {ch['sla']} | {ch['target']} {ch['unit']} | {ch['observed']} | {ch['status']} |"]
        md += ["", "| column | type | required | description |", "|---|---|---|---|"]
        for p in C.obj(c)["properties"]:
            md += [f"| `{p['name']}` | {p['physicalType']} | {'yes' if p['required'] else 'no'} | {p.get('description', '')} |"]
        md += [""]

        h.append(f"<h2>{html.escape(c['name'])} <span class='muted'>({domain})</span></h2>")
        h.append(
            f"<p><b>{html.escape(c['id'])}</b> v{c['version']} · owner {html.escape(C.owner(c))}<br>{html.escape(c['description']['purpose'])}</p>"
        )
        h.append("<table><tr><th>interface</th><th>contract</th><th>lifecycle</th><th>downstream jobs</th></tr>")
        for phys, ic, dep in ifaces:
            ds = f"{domain}.main.{phys}"
            cons = ", ".join(j for j in consumers_of(dg, ds) if not j.startswith(f"{domain}.")) or "none"
            h.append(
                f"<tr><td>{ds}</td><td>{ic['version']}</td><td>{'deprecated, retire after ' + dep if dep else 'latest'}</td><td>{html.escape(cons)}</td></tr>"
            )
        h.append("</table>")
        if r:
            h.append(f"<p>SLO status: <span class='{r['status']}'>{r['status']}</span> ({r['passed']}/{r['total']})</p>")
            h.append("<table><tr><th>SLA</th><th>target</th><th>observed</th><th>status</th></tr>")
            for ch in r["checks"]:
                h.append(
                    f"<tr><td>{ch['sla']}</td><td>{ch['target']} {ch['unit']}</td><td>{ch['observed']}</td><td class='{ch['status']}'>{ch['status']}</td></tr>"
                )
            h.append("</table>")
        h.append("<table><tr><th>column</th><th>type</th><th>required</th><th>description</th></tr>")
        for p in C.obj(c)["properties"]:
            h.append(
                f"<tr><td>{p['name']}</td><td>{p['physicalType']}</td><td>{'yes' if p['required'] else 'no'}</td><td>{html.escape(p.get('description', ''))}</td></tr>"
            )
        h.append("</table>")
    h.append("</body></html>")
    return "\n".join(md), "\n".join(h)
